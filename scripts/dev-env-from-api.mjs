// Writes .env.development.local for `next dev` from coact-api's .env, copying only the keys
// the dev /graphql proxy needs (src/proxy.js). Values are never printed.
//   node scripts/dev-env-from-api.mjs ../../coact-api/.env [http://localhost:8000]
import { readFileSync, writeFileSync } from "node:fs";

const [apiEnvPath, apiUrl = "http://localhost:8000"] = process.argv.slice(2);
if (!apiEnvPath) throw new Error("usage: node scripts/dev-env-from-api.mjs <path to coact-api/.env> [api url]");
const KEYS = ["DEV_MODE", "DEV_USERNAME", "USERNAME_FIELD", "EPPN_FIELD"];
const found = {};
for (const line of readFileSync(apiEnvPath, "utf8").split("\n")) {
  const m = line.match(/^\s*([A-Z_]+)\s*=\s*(.*)\s*$/);
  if (m && KEYS.includes(m[1])) found[m[1]] = m[2].replace(/^["']|["']$/g, "");
}
const lines = [`COACT_API_DEV_URL=${apiUrl}`, ...KEYS.filter((k) => k in found).map((k) => `${k}=${found[k]}`)];
writeFileSync(".env.development.local", `# generated by scripts/dev-env-from-api.mjs — local only, gitignored\n${lines.join("\n")}\n`);
console.log(`wrote .env.development.local (${Object.keys(found).join(", ")} + COACT_API_DEV_URL)`);
